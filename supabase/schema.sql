CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    telefone TEXT,
    origem TEXT,
    observacoes TEXT,
    criado_em DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS public.produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    custo_unitario DOUBLE PRECISION NOT NULL CHECK (custo_unitario >= 0),
    preco_venda DOUBLE PRECISION NOT NULL CHECK (preco_venda >= 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.vendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES public.clientes(id),
    data DATE NOT NULL,
    tipo TEXT NOT NULL,
    data_entrega DATE,
    pago BOOLEAN NOT NULL DEFAULT FALSE,
    entregue BOOLEAN NOT NULL DEFAULT FALSE,
    cancelada BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS public.itens_venda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id BIGINT NOT NULL REFERENCES public.vendas(id),
    produto_id BIGINT NOT NULL REFERENCES public.produtos(id),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario DOUBLE PRECISION NOT NULL,
    custo_unitario DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS public.gastos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL,
    categoria TEXT NOT NULL,
    descricao TEXT NOT NULL,
    valor DOUBLE PRECISION NOT NULL CHECK (valor >= 0)
);

CREATE TABLE IF NOT EXISTS public.ingredientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    unidade TEXT NOT NULL CHECK (unidade IN ('g', 'ml', 'un')),
    estoque_minimo DOUBLE PRECISION NOT NULL DEFAULT 0,
    tamanho_embalagem DOUBLE PRECISION
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_ingredientes_nome_lower
    ON public.ingredientes (lower(nome));

CREATE TABLE IF NOT EXISTS public.lotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingrediente_id BIGINT NOT NULL REFERENCES public.ingredientes(id),
    data DATE NOT NULL,
    local TEXT,
    quantidade DOUBLE PRECISION NOT NULL CHECK (quantidade > 0),
    restante DOUBLE PRECISION NOT NULL CHECK (restante >= 0),
    preco_total DOUBLE PRECISION NOT NULL CHECK (preco_total > 0),
    custo_unitario DOUBLE PRECISION NOT NULL,
    gasto_id BIGINT REFERENCES public.gastos(id)
);

CREATE TABLE IF NOT EXISTS public.receitas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL UNIQUE REFERENCES public.produtos(id),
    rendimento INTEGER NOT NULL CHECK (rendimento > 0)
);

CREATE TABLE IF NOT EXISTS public.itens_receita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receita_id BIGINT NOT NULL REFERENCES public.receitas(id) ON DELETE CASCADE,
    ingrediente_id BIGINT NOT NULL REFERENCES public.ingredientes(id),
    quantidade DOUBLE PRECISION NOT NULL CHECK (quantidade > 0),
    unidade TEXT,
    UNIQUE (receita_id, ingrediente_id)
);

CREATE TABLE IF NOT EXISTS public.producoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL,
    produto_id BIGINT NOT NULL REFERENCES public.produtos(id),
    unidades INTEGER NOT NULL CHECK (unidades > 0),
    custo_total DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS public.perdas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL,
    ingrediente_id BIGINT NOT NULL REFERENCES public.ingredientes(id),
    quantidade DOUBLE PRECISION NOT NULL,
    valor DOUBLE PRECISION NOT NULL,
    motivo TEXT
);

CREATE TABLE IF NOT EXISTS public.configuracoes (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    horas_mes DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (horas_mes >= 0),
    pro_labore DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (pro_labore >= 0),
    taxa_impostos_pct DOUBLE PRECISION NOT NULL DEFAULT 0
        CHECK (taxa_impostos_pct BETWEEN 0 AND 100),
    taxa_cartao_pct DOUBLE PRECISION NOT NULL DEFAULT 0
        CHECK (taxa_cartao_pct BETWEEN 0 AND 100),
    taxa_app_pct DOUBLE PRECISION NOT NULL DEFAULT 0
        CHECK (taxa_app_pct BETWEEN 0 AND 100),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO public.configuracoes (id)
VALUES (1)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.historico_precos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL
        REFERENCES public.produtos(id) ON DELETE RESTRICT,
    preco_anterior DOUBLE PRECISION NOT NULL CHECK (preco_anterior >= 0),
    preco_novo DOUBLE PRECISION NOT NULL CHECK (preco_novo >= 0),
    custo_anterior DOUBLE PRECISION NOT NULL CHECK (custo_anterior >= 0),
    custo_novo DOUBLE PRECISION NOT NULL CHECK (custo_novo >= 0),
    alterado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    origem TEXT
);

CREATE INDEX IF NOT EXISTS idx_historico_precos_produto_data
    ON public.historico_precos (produto_id, alterado_em DESC);

CREATE INDEX IF NOT EXISTS idx_vendas_cliente_id
    ON public.vendas (cliente_id);

CREATE INDEX IF NOT EXISTS idx_itens_venda_venda_id
    ON public.itens_venda (venda_id);

CREATE INDEX IF NOT EXISTS idx_itens_venda_produto_id
    ON public.itens_venda (produto_id);

CREATE INDEX IF NOT EXISTS idx_lotes_ingrediente_data
    ON public.lotes (ingrediente_id, data, id);

CREATE INDEX IF NOT EXISTS idx_lotes_gasto_id
    ON public.lotes (gasto_id);

CREATE INDEX IF NOT EXISTS idx_itens_receita_ingrediente_id
    ON public.itens_receita (ingrediente_id);

CREATE INDEX IF NOT EXISTS idx_producoes_produto_id
    ON public.producoes (produto_id);

CREATE INDEX IF NOT EXISTS idx_perdas_ingrediente_id
    ON public.perdas (ingrediente_id);
